// kem_key_sizes returns the (public_key, secret_key) sizes in bytes
// for the given KEM algorithm.
fn kem_key_sizes(algorithm KemAlgorithm) (int, int) {
	return match algorithm {
		.kyber512 { 800, 1632 }
		.kyber768 { 1184, 2400 }
		.kyber1024 { 1568, 3168 }
		.bike_l1 { 2542, 3110 }
		.bike_l3 { 4964, 5765 }
		.hqc128 { 2249, 2289 }
		.hqc192 { 4522, 4562 }
	}
}

// sig_key_sizes returns the (public_key, secret_key) sizes in bytes
// for the given signature algorithm.
fn sig_key_sizes(algorithm SigAlgorithm) (int, int) {
	return match algorithm {
		.dilithium2 { 1312, 2528 }
		.dilithium3 { 1952, 4000 }
		.dilithium5 { 2592, 4864 }
		.falcon512 { 897, 1281 }
		.falcon1024 { 1793, 2305 }
		.sphincs_sha256 { 32, 64 }
		.sphincs_sha256s { 32, 64 }
	}
}

