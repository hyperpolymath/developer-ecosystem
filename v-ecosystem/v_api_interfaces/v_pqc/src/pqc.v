// sig_verify verifies a signature against a message using the public
// key stored under the given label.
pub fn (s PqcServer) sig_verify(label string, message []u8, sig Signature) ! {
	kp := s.sig_keys[label] or {
		return error('signature key not found: ${label}')
	}
	// TODO: Perform real PQC signature verification with liboqs.
