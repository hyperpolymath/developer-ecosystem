// parse_kem_algorithm converts a string back to a KemAlgorithm enum.
fn parse_kem_algorithm(name string) KemAlgorithm {
	return match name {
		'kyber512' { .kyber512 }
		'kyber768' { .kyber768 }
		'kyber1024' { .kyber1024 }
		'bike_l1' { .bike_l1 }
		'bike_l3' { .bike_l3 }
		'hqc128' { .hqc128 }
		'hqc192' { .hqc192 }
		else { .kyber768 }
	}
}

// parse_sig_algorithm converts a string back to a SigAlgorithm enum.
fn parse_sig_algorithm(name string) SigAlgorithm {
	return match name {
		'dilithium2' { .dilithium2 }
		'dilithium3' { .dilithium3 }
		'dilithium5' { .dilithium5 }
		'falcon512' { .falcon512 }
		'falcon1024' { .falcon1024 }
		'sphincs_sha256' { .sphincs_sha256 }
		'sphincs_sha256s' { .sphincs_sha256s }
		else { .dilithium3 }
	}
}

// generate_random_bytes creates an array of random bytes of the
// specified length.
fn generate_random_bytes(length int) []u8 {
	mut bytes := []u8{len: length}
	for i in 0 .. length {
		bytes[i] = u8(rand.int_in_range(0, 256) or { 0 })
	}
	return bytes
}
