// sig_sign signs a message using the signature key stored under the
// given label.
pub fn (s PqcServer) sig_sign(label string, message []u8) !Signature {
	kp := s.sig_keys[label] or {
		return error('signature key not found: ${label}')
	}
	// TODO: Perform real PQC signing with liboqs.
	// Placeholder: HMAC-like hash of message with secret key.
	mut combined := []u8{}
	combined << kp.secret_key
	combined << message
	hash := sha256.sum(combined)
