// v_pqc — Post-Quantum Cryptography protocol types and server abstraction.
// Maps to proven-servers/protocols/proven-pqc.
//
// Provides KEM and digital signature operations for post-quantum algorithms.
// Supports ML-KEM (Kyber), ML-DSA (Dilithium), SLH-DSA (SPHINCS+), Falcon,
// BIKE, and HQC. Network I/O is stubbed with TODO markers; all type
// definitions and logic are real.
module v_pqc

import crypto.sha256
import rand

// KemAlgorithm enumerates the supported Key Encapsulation Mechanism
// algorithms. Kyber variants are NIST ML-KEM standardised; BIKE and
// HQC are candidates.
pub enum KemAlgorithm {
	kyber512
	kyber768
	kyber1024
	bike_l1
	bike_l3
	hqc128
	hqc192
}

// SigAlgorithm enumerates the supported post-quantum digital signature
// algorithms. Dilithium variants are NIST ML-DSA; Falcon and SPHINCS+
// are alternatives.
pub enum SigAlgorithm {
	dilithium2
	dilithium3
	dilithium5
	falcon512
	falcon1024
	sphincs_sha256
	sphincs_sha256s
}

// KeyPair holds a public/secret key pair generated by a PQC algorithm.
pub struct KeyPair {
pub:
	// public_key is the public key bytes.
	public_key []u8
	// secret_key is the secret (private) key bytes.
	secret_key []u8
	// algorithm identifies the KEM or signature algorithm used.
	algorithm string
}

// CipherText holds the output of a KEM encapsulation operation.
pub struct CipherText {
pub:
	// data is the encapsulated ciphertext.
	data []u8
	// algorithm identifies the KEM algorithm used.
	algorithm KemAlgorithm
	// shared_secret_hash is the SHA-256 hash of the shared secret,
	// for verification purposes only.
	shared_secret_hash []u8
}

// Signature holds the output of a PQC signing operation.
pub struct Signature {
pub:
	// data is the signature bytes.
	data []u8
	// algorithm identifies the signature algorithm used.
	algorithm SigAlgorithm
}

// PqcServer is the Post-Quantum Cryptography server. It manages key
// pairs and performs KEM and signature operations.
pub struct PqcServer {
pub:
	// name identifies this PQC server instance.
	name string
pub mut:
	// kem_keys stores KEM key pairs keyed by a label string.
	kem_keys map[string]KeyPair
	// sig_keys stores signature key pairs keyed by a label string.
	sig_keys map[string]KeyPair
}

// new_server creates a new PQC server instance.
pub fn new_server(name string) &PqcServer {
	return &PqcServer{
		name: name
		kem_keys: map[string]KeyPair{}
		sig_keys: map[string]KeyPair{}
	}
}

// kem_keygen generates a new KEM key pair for the specified algorithm
// and stores it under the given label.
pub fn (mut s PqcServer) kem_keygen(label string, algorithm KemAlgorithm) !KeyPair {
	if label.len == 0 {
		return error('key label must not be empty')
	}
	if label in s.kem_keys {
		return error('KEM key already exists: ${label}')
	}
	// Determine key sizes based on algorithm security level.
	pk_size, sk_size := kem_key_sizes(algorithm)
	// TODO: Use actual PQC library (e.g. liboqs FFI) for key generation.
	// Placeholder: generate random bytes of correct sizes.
	public_key := generate_random_bytes(pk_size)
	secret_key := generate_random_bytes(sk_size)
	kp := KeyPair{
		public_key: public_key
		secret_key: secret_key
		algorithm: kem_algorithm_name(algorithm)
	}
	s.kem_keys[label] = kp
	return kp
}

// kem_encapsulate performs a KEM encapsulation against the public key
// stored under the given label. Returns the ciphertext and the shared
// secret.
pub fn (s PqcServer) kem_encapsulate(label string) !(CipherText, []u8) {
	kp := s.kem_keys[label] or {
		return error('KEM key not found: ${label}')
	}
	// TODO: Perform real KEM encapsulation with liboqs.
	// Placeholder: derive shared secret from public key hash.
	shared_secret := generate_random_bytes(32)
	ss_hash := sha256.sum(shared_secret)
	// Ciphertext is derived from public key and shared secret.
	mut ct_input := []u8{}
	ct_input << kp.public_key
	ct_input << shared_secret
	ct_hash := sha256.sum(ct_input)
	algorithm := parse_kem_algorithm(kp.algorithm)
	ct := CipherText{
		data: ct_hash.to_array()
		algorithm: algorithm
		shared_secret_hash: ss_hash.to_array()
	}
	return ct, shared_secret
}

// kem_decapsulate performs a KEM decapsulation using the secret key
// stored under the given label. Returns the shared secret.
pub fn (s PqcServer) kem_decapsulate(label string, ciphertext CipherText) ![]u8 {
	if label !in s.kem_keys {
		return error('KEM key not found: ${label}')
	}
	kp := s.kem_keys[label] or { return error('KEM key not found: ${label}') }
	// TODO: Perform real KEM decapsulation with liboqs.
	// Placeholder: derive shared secret from secret key and ciphertext.
	mut input := []u8{}
	input << kp.secret_key
	input << ciphertext.data
	hash := sha256.sum(input)
	return hash.to_array()
}

